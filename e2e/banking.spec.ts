import { test, expect, connect, openDeposit, portfolio, certificate, admin, adminAction, eventArgs, P, I } from "./fixtures.js";

test("U01 connect, faucet, approve, open and reuse allowance", async ({ page, chain, wallet }) => {
  await connect(page);
  const before = await chain.token.balanceOf(wallet.account);
  await page.getByRole("button", { name: /Mint 1,000 USDC/ }).click();
  await expect.poll(() => chain.token.balanceOf(wallet.account)).toBe(before + P);
  await expect(page.getByRole("button", { name: /Mint 1,000 USDC/ })).toBeEnabled();
  // Approve 2,000 through UI, then open two 1,000 deposits. The second must skip approve.
  await page.locator(".form-card input").fill("2000");
  await page.getByRole("button", { name: /^Step 1\/2: Approve/ }).click();
  await expect(page.getByRole("button", { name: /^Step 2\/2: Open Deposit/ })).toBeEnabled();
  expect(await chain.token.allowance(wallet.account, chain.addresses.SavingCore)).toBe(2n * P);
  const coreBefore = await chain.token.balanceOf(chain.addresses.SavingCore);
  const id = await openDeposit(page, chain, wallet);
  expect(await chain.token.allowance(wallet.account, chain.addresses.SavingCore)).toBe(P);
  const count = wallet.receipts.length;
  await openDeposit(page, chain, wallet);
  expect(wallet.receipts.length - count).toBe(1);
  expect(await chain.token.allowance(wallet.account, chain.addresses.SavingCore)).toBe(0n);
  expect(await chain.token.balanceOf(chain.addresses.SavingCore)).toBe(coreBefore + 2n * P);
  expect(await chain.token.balanceOf(wallet.account)).toBe(before - P);
  await portfolio(page);
  await expect(certificate(page, id)).toBeVisible();
  wallet.evidence = { principalEach: P, count: 2, beforeBalance: before, afterBalance: before - P, allowance: 0n };
});

test("U02 early withdrawal pays principal less penalty and retains history", async ({ page, chain, wallet }) => {
  await connect(page);
  const id = await openDeposit(page, chain, wallet);
  const before = await chain.token.balanceOf(wallet.account);
  const feeReceiver = await chain.vault.feeReceiver();
  const feeBefore = await chain.token.balanceOf(feeReceiver);
  const vaultBefore = await chain.token.balanceOf(chain.addresses.VaultManager);
  const coreBefore = await chain.token.balanceOf(chain.addresses.SavingCore);
  await portfolio(page);
  await certificate(page, id).getByRole("button", { name: "Withdraw Early", exact: true }).click();
  await page.getByRole("button", { name: "Confirm Early Withdrawal", exact: true }).click();
  await expect.poll(async () => (await chain.core.getDeposit(id)).status).toBe(1n);
  const penalty = P * 350n / 10000n;
  expect(await chain.token.balanceOf(wallet.account)).toBe(before + P - penalty);
  expect(await chain.token.balanceOf(feeReceiver)).toBe(feeBefore + penalty);
  expect(await chain.token.balanceOf(chain.addresses.VaultManager)).toBe(vaultBefore);
  expect(await chain.token.balanceOf(chain.addresses.SavingCore)).toBe(coreBefore - P);
  eventArgs(chain, wallet, "Withdrawn");
  await expect(page.getByRole("dialog")).toContainText(/Success|Completed|Settled/i);
  await page.getByRole("dialog").getByRole("button", { name: "Back to Portfolio", exact: true }).click();
  await page.getByRole("tab", { name: /^Certificate History/ }).click();
  await expect(certificate(page, id)).toContainText("Withdrawn");
  wallet.evidence = { depositId: id, principal: P, penalty, beforeBalance: before, afterBalance: before + P - penalty, feeReceiver, feeBefore, feeAfter: feeBefore + penalty, vaultBefore, vaultAfter: vaultBefore };
});

